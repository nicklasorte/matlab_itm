"""Check that a regenerated input CSV reproduces the stored one.

Usage: python3 compare_inputs.py NEW.csv STORED.csv [ROWS]

Passes when the files are byte-identical, or when every field agrees to
1e-14 relative. numpy's exp and log take different SIMD paths on different
processors (for example with and without AVX-512), so gen_cases.py can move
the last bit of a generated input on another machine; the stored inputs,
not regenerated ones, feed the expected values. ROWS limits the check to the
first ROWS data rows. Exits 1 on any larger difference.
"""
import sys


def main(new_file, stored_file, rows=None):
    new = open(new_file).read().splitlines()
    old = open(stored_file).read().splitlines()
    if rows is not None:
        old = old[:rows + 1]
    name = stored_file.split("/")[-1]
    if new == old:
        print(f"ok   {name}: regenerated byte for byte ({len(old) - 1 if ',' in old[0] and not old[0][0].isdigit() else len(old)} lines)")
        return 0
    if len(new) != len(old):
        print(f"FAIL {name}: {len(new)} lines vs {len(old)} stored")
        return 1
    worst, nbits = 0.0, 0
    for i, (a, b) in enumerate(zip(new, old)):
        if a == b:
            continue
        fa, fb = a.split(","), b.split(",")
        if len(fa) != len(fb):
            print(f"FAIL {name}: line {i + 1} has {len(fa)} fields vs {len(fb)}")
            return 1
        for x, y in zip(fa, fb):
            if x == y:
                continue
            try:
                u, v = float(x), float(y)
            except ValueError:
                print(f"FAIL {name}: line {i + 1}: {x} vs stored {y}")
                return 1
            rel = abs(u - v) / max(abs(v), 1e-300)
            if rel > 1e-14:
                print(f"FAIL {name}: line {i + 1}: {x} vs stored {y}")
                return 1
            worst, nbits = max(worst, rel), nbits + 1
    print(f"ok   {name}: {nbits} values differ in the last bits (largest {worst:.1g} relative); "
          "numpy's SIMD exp and log on this processor")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else None))
